# -*- coding: utf-8 -*-
"""
KazualCipher — графическая оболочка, режимы работы и ускорители для
семейства блочных шифров Kazual (Kazual-512 и Kazual-64).

Подпакеты:
    kazual.cipher  эталонная реализация шифров + native.py (numba JIT:
                   ГОРН и Kazual-512 в машинном коде, параллельно по ядрам)
    kazual.modes   контейнер v2 (самоописание), SIV (+ параллельный
                   tree-MAC), ECB, CTR, PKCS#7
    kazual.stream  потоковые конвейеры: файлы любого размера с постоянным
                   потреблением ОЗУ, пакетная обработка, отмена, .part-файлы
    kazual.config  система конфигураций (JSON + встроенные значения)
    kazual.kdf     Argon2id (PHC-параметры) и вывод ключей
    kazual.engine  высокоуровневый фасад, который используют GUI и CLI
    kazual.app     графический интерфейс (PySide6)

Запуск:  python main.py  — при нехватке зависимостей main.py сам создаст
окружение и установит их (консоль установки откроется автоматически).

ДИСКЛЕЙМЕР: экспериментальная учебная конструкция, не проходила
независимого криптоанализа и не предназначена для защиты реальных данных.
"""

__version__ = '1.1.1'
__author__ = 'KazualCipher contributors'
__license__ = 'MIT'


def missing_deps_hint(exc: Exception) -> str:
    """Подсказка при нехватке зависимостей (для запуска из терминала).

    main.py при нехватке зависимостей ставит их сам (bootstrap-консоль);
    эта справка — для ручного запуска `python -m kazual …` без main.py.
    """
    return (
        '\n'
        '  KazualCipher: не хватает зависимостей (%s).\n'
        '\n'
        '  Проще всего: запустите  python main.py  (или двойной клик по\n'
        '  main.py) — программа сама создаст окружение .venv и установит\n'
        '  всё необходимое, затем откроется окно.\n'
        '\n'
        '  Вручную:\n'
        '      python -m pip install -r requirements.txt\n'
        '\n' % exc
    )
